"""Add one validated, benchmarked LLM-factory task to the team4 submission folder, then rebuild the ZIP.

    uv run python -m factory.add_to_submission <iid> <submission_dir> [--dry-run]

Copies generated_tasks/<iid> into <submission_dir>/generated_tasks/, appends a telemetry row to
<submission_dir>/pipeline_run.json (from runs/<iid>/summary.json), copies its benchmark evidence to
<submission_dir>/evidence/llm_factory/<iid>/, and appends a disclosure paragraph to the README.
Refuses unless summary ok=true and a complete benchmark.json exists.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    iid, sub = sys.argv[1], Path(sys.argv[2])
    dry = "--dry-run" in sys.argv
    run = ROOT / "runs" / iid
    summ = json.loads((run / "summary.json").read_text())
    bench = json.loads((run / "benchmark.json").read_text()) if (run / "benchmark.json").exists() else None
    if not summ.get("ok"):
        raise SystemExit(f"{iid}: not valid (summary ok=false)")
    if not dry and not (bench and bench.get("complete")):
        raise SystemExit(f"{iid}: no complete benchmark.json")
    dst = sub / "generated_tasks" / iid
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(ROOT / "generated_tasks" / iid, dst)
    pr = json.loads((sub / "pipeline_run.json").read_text())
    pr["tasks"] = [t for t in pr["tasks"] if t["instance_id"] != iid] + [{
        "instance_id": iid, "model": summ.get("model"), "wall_seconds": summ.get("wall_seconds"),
        "model_calls": summ.get("model_calls"), "attempts": summ.get("attempts"),
        "n_input_tokens": summ.get("n_input_tokens"), "n_output_tokens": summ.get("n_output_tokens"),
        "n_cache_tokens": summ.get("n_cache_tokens"), "cost_usd": summ.get("cost_usd"),
        "first_pass_valid": summ.get("attempts") == 1, "generator": "track1_llm_factory (LLM path)",
        "record": f"evidence/llm_factory/{iid}/"}]
    (sub / "pipeline_run.json").write_text(json.dumps(pr, indent=1))
    ev = sub / "evidence" / "llm_factory" / iid
    ev.mkdir(parents=True, exist_ok=True)
    for f in ("summary.json", "design.json", "final_result.json", "benchmark.json"):
        if (run / f).exists():
            shutil.copy(run / f, ev / f)
    res = f"resolve@3 = {bench['resolve_at_3']}" if bench else "benchmark pending (dry run)"
    readme = sub / "README.md"
    readme.write_text(readme.read_text() + f"""

## Additional task from the LLM factory: `{iid}`

Generated by the team's second pipeline (`track1_llm_factory/` in the repo): an LLM generator
(Claude Fable 5.2 / Sonnet 5.5 via the organizer OpenRouter key) with blind tests, mechanical +
LLM fairness gates, Codex's Docker/Harbor checker (oracle 1.0, nop 0.0, semantic gold mutation)
and a difficulty feedback loop. Haiku 5.5 (terminus-2, k=3): **{res}**. Telemetry is the last row
of `pipeline_run.json`; evidence in `evidence/llm_factory/{iid}/`. Its design passed independent
fairness reviews (Claude Fable 5.2 and Codex) before packaging. Full attempt ledger (all attempts,
failures and cost) is in the repo at `track1_llm_factory/evidence/YIELD_REPORT.md`.
""")
    print(f"added {iid} -> {dst}")


if __name__ == "__main__":
    main()
